"""Manual-KPI templates generated from the sector modules (so templates never drift from configs).

data/manual/templates/<archetype>_kpis.csv: one row per manual KPI (inherited ones included) x fiscal year,
columns metric,fiscal_year,value,unit,source_url,source_date,verified with value/source/date/verified blank.
"""
from __future__ import annotations

import csv
from pathlib import Path
from typing import List

from .standardise import fy_year, year_label

COLUMNS = ["metric", "fiscal_year", "value", "unit", "source_url", "source_date", "verified"]


def year_range(spec: str) -> List[str]:
    a, b = [x.strip().upper() for x in spec.split("-")]
    return [year_label(y) for y in range(fy_year(a), fy_year(b) + 1)]


def template_rows(sector, years: List[str]) -> List[List[str]]:
    rows = []
    kpis = sorted(sector.manual_kpis.values(), key=lambda k: (not k.get("required"), k["id"]))
    for k in kpis:
        for y in years:
            rows.append([k["id"], y, "", k["unit"], "", "", ""])
    return rows


def write_templates(cfg, years_spec: str = "FY22-FY26") -> List[Path]:
    years = year_range(years_spec)
    out_dir = cfg.paths.manual_dir / "templates"
    out_dir.mkdir(parents=True, exist_ok=True)
    paths = []
    for arch, sec in sorted(cfg.sectors.items()):
        p = out_dir / f"{arch}_kpis.csv"
        with p.open("w", newline="") as fh:
            w = csv.writer(fh)
            w.writerow(COLUMNS)
            w.writerows(template_rows(sec, years))
        paths.append(p)
    return paths


# ---------------------------------------------------------------------------------------------- coverage report
BLOWUP_YEARS = "FY14-FY18"


def target_years(row: dict, default_spec: str = "FY22-FY26") -> List[str]:
    """Years the manual KPIs should cover for a universe row: FY22-FY26, plus FY14-FY18 for blow-up companies."""
    years = year_range(default_spec)
    if str(row.get("role", "")).strip().lower() == "blowup":
        years = year_range(BLOWUP_YEARS) + years
    return years


def _read_kpis(path: Path) -> dict:
    """{(metric, FY): row} for the non-blank values of a v2 manual-KPI file (empty if absent)."""
    out = {}
    if not path.exists():
        return out
    with path.open(newline="") as fh:
        for r in csv.DictReader(fh):
            if (r.get("value") or "").strip():
                out[(r["metric"].strip(), r["fiscal_year"].strip().upper())] = r
    return out


def coverage(cfg, default_spec: str = "FY22-FY26") -> List[dict]:
    """Per company x KPI: which target years have a sourced value. Deterministic; reads data/manual/<TICKER>_kpis.csv."""
    rows = []
    for t, u in cfg.universe.items():
        sec = cfg.sectors[cfg.archetype_of(t)]
        years = target_years(u, default_spec)
        have = _read_kpis(cfg.paths.manual_file(t))
        for k in sorted(sec.manual_kpis.values(), key=lambda k: (not k.get("required"), k["id"])):
            found = [y for y in years if (k["id"], y) in have]
            verified = sum(1 for y in found if have[(k["id"], y)].get("verified", "N").strip().upper() == "Y")
            rows.append({"ticker": t, "archetype": sec.archetype, "kpi": k["id"], "required": bool(k.get("required")),
                         "years": years, "found": found, "verified": verified})
    return rows


def coverage_markdown(cfg, default_spec: str = "FY22-FY26") -> str:
    rows = coverage(cfg, default_spec)
    lines = ["# Manual KPI coverage", "",
             "Generated by `python -m engine kpi-coverage` from `data/manual/<TICKER>_kpis.csv` and the sector modules.",
             "Target years: FY22-FY26 for every company, plus FY14-FY18 for blow-up companies. A year counts as found",
             "only when the file has a value with a source URL and date; blanks mean no source stated the value",
             "(values are never estimated). `verified = Y` means the value was checked in the primary document;",
             "`N` means it was taken from the cited page's search extract.", "",
             "## Summary (required KPIs)", "",
             "| Ticker | Archetype | Required KPI-years found | Optional KPI-years found | Verified |",
             "|---|---|---|---|---|"]
    by_t = {}
    for r in rows:
        by_t.setdefault((r["ticker"], r["archetype"]), []).append(r)
    for (t, a), rs in by_t.items():
        req = [r for r in rs if r["required"]]
        opt = [r for r in rs if not r["required"]]
        rf, rt = sum(len(r["found"]) for r in req), sum(len(r["years"]) for r in req)
        of, ot = sum(len(r["found"]) for r in opt), sum(len(r["years"]) for r in opt)
        ver = sum(r["verified"] for r in rs)
        lines.append(f"| {t} | {a} | {rf}/{rt} ({rf / rt:.0%}) | {of}/{ot} | {ver} |" if rt else
                     f"| {t} | {a} | - | {of}/{ot} | {ver} |")
    lines += ["", "## Detail (required KPIs; missing years are blank in the file)", ""]
    for (t, a), rs in by_t.items():
        lines += [f"### {t} ({a})", "", "| KPI | Found | Missing |", "|---|---|---|"]
        for r in rs:
            if not r["required"] and not r["found"]:
                continue
            miss = [y for y in r["years"] if y not in r["found"]]
            tag = "" if r["required"] else " (optional)"
            lines.append(f"| `{r['kpi']}`{tag} | {', '.join(r['found']) or '-'} | {', '.join(miss) or '-'} |")
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def write_coverage(cfg, default_spec: str = "FY22-FY26") -> Path:
    p = cfg.paths.manual_dir / "COVERAGE.md"
    p.write_text(coverage_markdown(cfg, default_spec))
    return p
